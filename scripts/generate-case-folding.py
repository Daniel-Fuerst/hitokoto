"""Generates src/core/src/case_folding_table.inc from Unicode's CaseFolding.txt (ADR 0008).

Only the simple mappings (status C and S, one code point to one) are kept. Run by hand when the
Unicode version is raised, then review the diff of the generated file:

    python3 scripts/generate-case-folding.py CaseFolding.txt src/core/src/case_folding_table.inc

CaseFolding.txt: https://www.unicode.org/Public/<version>/ucd/CaseFolding.txt
"""
import re
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    source, target = sys.argv[1], sys.argv[2]
    with open(source, encoding="utf-8") as f:
        text = f.read()
    version = re.search(r"CaseFolding-(\d+\.\d+\.\d+)\.txt", text)
    if not version:
        print("no version line (# CaseFolding-x.y.z.txt) in " + source, file=sys.stderr)
        return 1
    owner = re.search(r"^# \u00a9 (\d{4}) Unicode", text, re.M)
    copyright = "(c) " + (owner.group(1) if owner else "Unicode")
    mappings = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping = (field.strip() for field in line.split(";")[:3])
        if status not in ("C", "S"):
            continue
        targets = mapping.split()
        if len(targets) != 1:
            print("not one to one: " + line, file=sys.stderr)
            return 1
        mappings.append((int(code, 16), int(targets[0], 16)))
    mappings.sort()
    for (a, _), (b, _) in zip(mappings, mappings[1:]):
        if a == b:
            print("duplicate mapping for %04X" % a, file=sys.stderr)
            return 1
    out = [
        "// SPDX-License-Identifier: GPL-3.0-or-later AND Unicode-3.0",
        "// Generated by scripts/generate-case-folding.py from CaseFolding-%s.txt; do not edit." % version.group(1),
        "// Simple case folding (status C and S), one code point to one, sorted by code point (ADR 0008).",
        "// Data: %s Unicode, Inc. Unicode Character Database, terms of use and licence:" % copyright,
        "// https://www.unicode.org/terms_of_use.html (Unicode License v3)",
        "",
        'constexpr std::string_view kCaseFoldingVersion = "%s";' % version.group(1),
        "",
        "constexpr std::array<CaseFoldingEntry, %d> kCaseFolding{{" % len(mappings),
    ]
    row = []
    for a, b in mappings:
        row.append("{0x%04X, 0x%04X}," % (a, b))
        if len(row) == 6:
            out.append("    " + " ".join(row))
            row = []
    if row:
        out.append("    " + " ".join(row))
    out.append("}};")
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("%d mappings, Unicode %s" % (len(mappings), version.group(1)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
